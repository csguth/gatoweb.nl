// Runtime i18n (EN/NL/PT) for the strings JavaScript builds on the fly: booking
// messages, invoice line items, auth errors, ... Static page copy is no longer handled
// here — Hugo compiles it into each language's page from i18n/*.toml.
//
// The language is therefore not a runtime user choice anymore: it is whatever page the
// visitor is on (<html lang>, rendered by Hugo). Switching language means navigating to
// /en/, /nl/ or /pt/, not mutating the current DOM.
(function () {
  const STORAGE_KEY = 'gatoweb_lang';
  const DEFAULT_LANG = 'en';
  const SUPPORTED_LANGS = ['en', 'nl', 'pt'];
  let initPromise = null;

  function normalizeLanguage(lang) {
    if (!lang) return DEFAULT_LANG;
    const normalized = String(lang).toLowerCase().split('-')[0];
    return SUPPORTED_LANGS.indexOf(normalized) !== -1 ? normalized : DEFAULT_LANG;
  }

  function getPageLanguage() {
    const fromDocument = document.documentElement.lang;
    if (fromDocument) return normalizeLanguage(fromDocument);
    // Standalone documents generated by JS itself (e.g. the printable invoice opened in
    // a new tab) have no Hugo-rendered <html lang>; fall back to the saved preference.
    let stored = null;
    try {
      stored = localStorage.getItem(STORAGE_KEY);
    } catch (e) { /* localStorage unavailable — ignore. */ }
    return normalizeLanguage(stored || navigator.language);
  }

  async function loadResources() {
    const resources = {};
    for (const lang of SUPPORTED_LANGS) {
      // Absolute path: pages live under /en/, /nl/ and /pt/, so a relative URL would
      // resolve to e.g. /en/locales/en.json and 404.
      const response = await fetch('/locales/' + lang + '.json');
      if (!response.ok) {
        throw new Error('Failed to load locale file: /locales/' + lang + '.json');
      }
      resources[lang] = { translation: await response.json() };
    }
    return resources;
  }

  async function init() {
    if (initPromise) return initPromise;
    initPromise = (async function () {
      if (!window.i18next) {
        throw new Error('i18next global not found');
      }
      const resources = await loadResources();
      await window.i18next.init({
        lng: getPageLanguage(),
        fallbackLng: DEFAULT_LANG,
        resources: resources,
        interpolation: { escapeValue: false }
      });
      document.dispatchEvent(new CustomEvent('gato:i18n-ready', { detail: { language: window.i18next.language } }));
      return window.i18next.language;
    })();
    return initPromise;
  }

  function getLanguage() {
    if (window.i18next && window.i18next.isInitialized) {
      return normalizeLanguage(window.i18next.language);
    }
    return getPageLanguage();
  }

  function t(key, options) {
    if (window.i18next && window.i18next.isInitialized) {
      return window.i18next.t(key, options);
    }
    return key;
  }

  window.__gatoI18n = {
    init: init,
    t: t,
    getLanguage: getLanguage,
    normalizeLanguage: normalizeLanguage
  };
  window.t = t;

  // The old langToggle() Alpine component used to bootstrap this runtime; with
  // compile-time i18n there is no toggle component anymore, so start it here. Callers
  // that need the strings still await __gatoI18n.init(), which reuses this same
  // promise.
  init().catch(function (error) {
    console.error('Could not initialize the i18n runtime', error);
  });
})();
